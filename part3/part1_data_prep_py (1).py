def generate_structured_water_report(ph_level, hardness, sulfate, chloramines):
    print(f"\n--- Sending Water Metrics to LLM for Structured Analysis ---")

    # We create a prompt that explicitly demands a structured JSON output
    prompt = f"""
    You are an expert environmental data scientist. Analyze the following water quality metrics:
    - pH Level: {ph_level}
    - Hardness: {hardness} mg/L
    - Sulfate: {sulfate} mg/L
    - Chloramines: {chloramines} ppm

    Provide your analysis strictly as a valid JSON object. Do not include any conversational text, markdown blocks like ```json, or introductory phrasing outside the JSON. The JSON must follow this exact structure:
    {{
        "ph_evaluation": "A description of the acidity/alkalinity and its safety implications.",
        "chemical_balance": "An assessment of the hardness, sulfates, and chloramines.",
        "safety_status": "Safe, Action Required, or Unsafe",
        "recommended_treatment": "Specific action steps to normalize the water quality."
    }}
    """

    # Pack the prompt into the required messages format
    messages = [{"role": "user", "content": prompt}]

    # Call your working API function
    api_response = call_api(messages)

    # Extract the raw string response from the text response dictionary structure
    raw_content = api_response["message"]["content"].strip()

    # Clean up any potential markdown backticks that the LLM might have accidentally included
    if raw_content.startswith("```json"):
        raw_content = raw_content.replace("```json", "", 1).replace("```", "", 1).strip()
    elif raw_content.startswith("```"):
        raw_content = raw_content.replace("```", "", 2).strip()

    try:
        # Parse the string into an actual JSON object to demonstrate structured handling
        structured_json = json.loads(raw_content)
        print("✅ Successfully received and parsed structured JSON response from LLM!")
        return structured_json
    except json.JSONDecodeError:
        print("❌ Error: LLM output could not be parsed as valid JSON.")
        print("Raw output was:", raw_content)
        return None

