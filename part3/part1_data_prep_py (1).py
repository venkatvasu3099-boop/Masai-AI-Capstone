    plt.figure(figsize=(8, 5))
    sns.countplot(data=df, x='Hardness_Category', palette='viridis')
    plt.title('Distribution of Water Hardness Categories')
    plt.xlabel('Hardness Category')
    plt.ylabel('Count')
    plt.tight_layout()
    plt.savefig('plots/hardness_category_counts.png') # Mandatory per submission guidelines
    plt.close()
    print("Saved: plots/hardness_category_counts.png")

    # 3. Correlation Heatmap (Numeric only)
    plt.figure(figsize=(10, 8))
    # Select only numeric columns for correlation to avoid errors
